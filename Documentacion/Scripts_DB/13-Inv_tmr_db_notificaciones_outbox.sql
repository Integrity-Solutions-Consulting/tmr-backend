-- Crear schema 'notificacion'
CREATE SCHEMA IF NOT EXISTS notificacion;

-- ============================================================================
-- 1. TABLA: notificacion.notificacion_envio (Flujos 1, 2 y 3)
-- ============================================================================
CREATE TABLE IF NOT EXISTS notificacion.notificacion_envio (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INT NOT NULL,
    inicio_periodo DATE NOT NULL,
    fin_periodo DATE NOT NULL,
    fecha_corte TIMESTAMPTZ NULL,
    origen VARCHAR(20) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    horas_faltantes NUMERIC(6, 2) NOT NULL,
    id_usuario_ejecutor INT NULL,
    fecha_envio TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    detalle_error TEXT NULL,

    -- Clave foránea referenciando a la tabla de empleados
    CONSTRAINT fk_notificacion_envio_empleado 
        FOREIGN KEY (id_empleado) 
        REFERENCES administracion.tbl_administracion_empleado(id)
);

-- Índice único condicional: máximo un aviso por corte solo para automáticos
CREATE UNIQUE INDEX IF NOT EXISTS uq_idx_notificacion_envio_auto 
    ON notificacion.notificacion_envio (id_empleado, fecha_corte) 
    WHERE origen = 'Automatico';


-- ============================================================================
-- 2. TABLA: notificacion.notificacion_fecha_corte (Flujo 3)
-- ============================================================================
CREATE TABLE IF NOT EXISTS notificacion.notificacion_fecha_corte (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INT NOT NULL,
    mes INT NOT NULL CHECK (mes BETWEEN 1 AND 12),
    tipo VARCHAR(20) NOT NULL,
    inicio_periodo DATE NOT NULL,
    fin_periodo DATE NOT NULL,
    fecha_corte TIMESTAMPTZ NOT NULL,
    ejecutada BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_ejecucion TIMESTAMPTZ NULL,
    id_usuario_creador INT NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Un solo corte de cada tipo por mes
    CONSTRAINT uq_notificacion_fecha_corte_periodo 
        UNIQUE (anio, mes, tipo)
);


-- ============================================================================
-- 3. TABLA: notificacion.evento_outbox (Flujos 1, 2 y 3)
-- ============================================================================
CREATE TABLE IF NOT EXISTS notificacion.evento_outbox (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tipo_evento VARCHAR(100) NOT NULL,
    payload JSONB NOT NULL,
    estado VARCHAR(20) NOT NULL,
    intentos INT NOT NULL DEFAULT 0,
    ultimo_error TEXT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_procesado TIMESTAMPTZ NULL
);

-- Índice para consultar rápidamente los eventos pendientes
CREATE INDEX IF NOT EXISTS idx_evento_outbox_estado_fecha 
    ON notificacion.evento_outbox (estado, fecha_creacion);
