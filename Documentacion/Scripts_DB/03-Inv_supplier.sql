-- Es idempotente y no elimina ni modifica datos existentes fuera de estas dos tablas.
-- Ejecutar primero en desarrollo, validar y luego promover por el proceso de despliegue.

BEGIN;

CREATE SCHEMA IF NOT EXISTS inventory;

CREATE TABLE IF NOT EXISTS inventory.supplier_type (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(150) NOT NULL,
    status            BOOLEAN NOT NULL DEFAULT TRUE,
    creation_user     VARCHAR(100),
    modification_user VARCHAR(100),
    creation_date     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modification_date TIMESTAMPTZ,
    CONSTRAINT uq_supplier_type_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS inventory.supplier (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_name     VARCHAR(150) NOT NULL,
    address           VARCHAR(255),
    phone             VARCHAR(20),
    email             VARCHAR(100),
    ruc               VARCHAR(13),
    id_supplier_type  INTEGER NOT NULL,
    status            BOOLEAN NOT NULL DEFAULT TRUE,
    creation_user     VARCHAR(100),
    modification_user VARCHAR(100),
    creation_date     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    modification_date TIMESTAMPTZ,
    CONSTRAINT fk_supplier_type
        FOREIGN KEY (id_supplier_type) REFERENCES inventory.supplier_type(id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT chk_supplier_email CHECK (email IS NULL OR email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_supplier_ruc
    ON inventory.supplier (ruc) WHERE ruc IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_supplier_type_status
    ON inventory.supplier (id_supplier_type, status);
CREATE INDEX IF NOT EXISTS ix_supplier_business_name
    ON inventory.supplier (business_name);

