-- Extensión del Módulo de Solicitudes de Permisos y Vacaciones:
--   1. Flags de control en time_report.tbl_time_report_solicitud:
--      - descuenta_vacaciones : indica si el permiso descuenta del saldo anual
--      - es_recuperable       : indica si el permiso es recuperable
--      - es_anticipada        : marca vacaciones adelantadas contra ciclo futuro
--      - es_historico         : distingue carga histórica migrada desde Excel
--      - verificado_rrhh      : bandera de revisión por Talento Humano
--      - observacion_migracion: notas de auditoría/migración (ej. falta doc.)
--   2. Tabla time_report.tbl_time_report_ajuste_vacaciones:
--      - Ajustes manuales de saldo (+/- días) y excepciones de vacaciones para
--        colaboradores bajo régimen de Factura / Servicios Profesionales.
--
-- Garantías:
--   * Transaccional (BEGIN / COMMIT) e idempotente.
--   * No altera el DDL de los esquemas administracion ni autenticacion.
-- ============================================================================

BEGIN;

-- 1. Columnas adicionales en time_report.tbl_time_report_solicitud
ALTER TABLE time_report.tbl_time_report_solicitud
    ADD COLUMN IF NOT EXISTS descuenta_vacaciones  BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS es_recuperable        BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS es_anticipada         BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS es_historico          BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS verificado_rrhh       BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS observacion_migracion TEXT    NULL;

-- Asegurar que toda solicitud de tipo VACACIONES existente descuente vacaciones
UPDATE time_report.tbl_time_report_solicitud s
SET descuenta_vacaciones = TRUE
FROM time_report.tbl_time_report_tipo_permiso t
WHERE s.id_tipo_permiso = t.id
  AND t.codigo = 'VACACIONES'
  AND s.descuenta_vacaciones = FALSE;

CREATE INDEX IF NOT EXISTS idx_tr_solicitud_verificado_rrhh
    ON time_report.tbl_time_report_solicitud (verificado_rrhh, fecha_inicio DESC)
    WHERE activo = TRUE;

CREATE INDEX IF NOT EXISTS idx_tr_solicitud_descuenta_vac
    ON time_report.tbl_time_report_solicitud (id_empleado, descuenta_vacaciones)
    WHERE activo = TRUE;

-- 2. Tabla de ajustes manuales y excepciones de vacaciones por colaborador
CREATE TABLE IF NOT EXISTS time_report.tbl_time_report_ajuste_vacaciones (
    id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado          INT           NOT NULL,
    tipo_ajuste          VARCHAR(30)   NOT NULL,
    dias_ajuste          NUMERIC(6, 2) NOT NULL DEFAULT 0,
    permite_vacaciones   BOOLEAN       NULL,
    motivo               TEXT          NOT NULL,
    activo               BOOLEAN       NOT NULL DEFAULT TRUE,
    usuario_creacion     VARCHAR(50)   NOT NULL,
    fecha_creacion       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    usuario_modificacion VARCHAR(50)   NULL,
    fecha_modificacion   TIMESTAMPTZ   NULL,
    ip_creacion          VARCHAR(45)   NOT NULL,
    ip_modificacion      VARCHAR(45)   NULL,

    CONSTRAINT fk_tr_ajuste_vacaciones_empleado
        FOREIGN KEY (id_empleado) REFERENCES administracion.tbl_administracion_empleado(id),
    CONSTRAINT ck_tr_ajuste_vacaciones_tipo
        CHECK (tipo_ajuste IN ('AJUSTE_DIAS', 'EXCEPCION_FACTURA')),
    CONSTRAINT ck_tr_ajuste_vacaciones_motivo
        CHECK (NULLIF(BTRIM(motivo), '') IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_tr_ajuste_vacaciones_empleado
    ON time_report.tbl_time_report_ajuste_vacaciones (id_empleado, fecha_creacion DESC)
    WHERE activo = TRUE;

COMMIT;
